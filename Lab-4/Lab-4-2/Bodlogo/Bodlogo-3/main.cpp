
// Хэрэглэгчээс тоо авч, тухайн тоо анхны тоо мөн эсэхийг while давталт ашиглан шалга.

#include <stdio.h>

int main() {
    int n, i = 2, prime = 1;

    printf("Тоогоо оруулна уу: ");
    scanf("%d", &n);

    if (n < 2) {
        prime = 0;
    }

    while (i < n) {
        if (n % i == 0) {
            prime = 0;
        }
        i++;
    }

    if (prime == 1)
        printf("Анхны тоо мөн.\n");
    else
        printf("Анхны тоо биш.\n");

    return 0;
}
