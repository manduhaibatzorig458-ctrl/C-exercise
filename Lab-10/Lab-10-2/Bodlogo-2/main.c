#include <stdio.h>                  // printf, gets ашиглах сан
#include <stdlib.h>                 // system("pause") ашиглах сан
#define MAX_SIZE 100                // мөрийн дээд хэмжээ (100 тэмдэгт)

int main()
{
    char text[MAX_SIZE];            // 100 тэмдэгт багтах мөр зарлана
    int i;                          // давталтын тоолуур (индекс)
    int count = 0;                  // тэмдэгтийн тоо, эхлээд 0

    /* Хэрэглэгчээс мөр оруулахыг хүсч, уншина */
    printf("Enter any string: ");   // мөр оруулахыг хүснэ
    gets(text);                     // мөрийг гараас text хувьсагчид уншина

    /* Мөрийн төгсгөлийн тэмдэгт '\0' хүртэл давтана */
    for (i = 0; text[i] != '\0'; i++)
    {
        count++;                    // тэмдэгт бүрт тоолуурыг 1-ээр нэмнэ
    }

    /* Үр дүнг хэвлэнэ */
    printf("Length of '%s' = %d", text, count);   // мөр ба уртыг хэвлэнэ
    printf("\n");                   // шинэ мөр рүү орно
    system("pause");                // дэлгэцийг хаахгүй, товч дарахыг хүлээнэ

    return 0;                       // програм амжилттай дууслаа
}