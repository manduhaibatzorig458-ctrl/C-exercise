#include <stdio.h>

int main() { 
    int A[8];
    int X, count = 0;   

    printf("8 элементийг оруулна уу:\n");
    for (int i = 0; i < 8; i++) {
        scanf("%d", &A[i]);
    }

    printf("X тоог оруулна уу: ");
    scanf("%d", &X);

    printf("X-ээс бага элементүүд:\n");
    for (int i = 0; i < 8; i++) {
        if (A[i] < X) {
            printf("A[%d] = %d\n", i, A[i]);
            count++;
        }
    }

    printf("X-ээс бага элементийн тоо: %d\n", count);
    return 0;
}


